#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// bb 3.0.0-nightly.20251104 still emits calculateProofSize($LOG_N).
// Size folding is still required: with solc 0.8.30, Cancun, optimizer runs=200,
// non-IR and bytecode_hash=none, raw runtime is 24,602 bytes (>24,576 EIP-170);
// the folded verifier is 24,321 bytes. A Forge test enforces the deployment cap.
// Unlike the old depth-10 circuit, this circuit has LOG_N=11: bb's arithmetic
// yields 222 proof fields, not the old literal 210. Derive this from bb output,
// fold only its size-check call, and retain the protocol and Apache-2.0 header.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { projectRoot, run, sha256 } from './build-circuit.mjs';

export function generateVerifier(artifactDirectory = join(projectRoot, 'artifacts'),
  outputPath = join(projectRoot, 'contracts/src/MembershipVoteVerifier.sol')) {
  mkdirSync(dirname(outputPath), { recursive: true });
  run('bb', ['write_solidity_verifier', '-s', 'ultra_honk', '-k',
    join(artifactDirectory, 'membership_vote.vk'), '-o', outputPath, '--optimized']);
  let source = readFileSync(outputPath, 'utf8');
  if (!source.startsWith('// SPDX-License-Identifier: Apache-2.0')) {
    throw new Error('Unexpected bb verifier license');
  }
  const constants = Object.fromEntries([...source.matchAll(/uint256 constant (\w+) = (\d+);/g)]
    .map((match) => [match[1], Number(match[2])]));
  const body = source.match(/function calculateProofSize\(uint256 logN\)[^{]+\{([\s\S]*?)\n    \}/)?.[1];
  if (!body || !constants.LOG_N) throw new Error('Unexpected bb proof size function');
  let proofLength = 0;
  for (const match of body.matchAll(/(?:uint256 )?proofLength (\+?=) ([^;]+);/g)) {
    const expression = match[2].replace(/\b([A-Za-z_]\w*)\b/g, (name) => {
      if (name === 'logN') return String(constants.LOG_N);
      if (constants[name] === undefined) throw new Error(`Unknown bb constant: ${name}`);
      return String(constants[name]);
    });
    if (!/^[\d\s+*()\-/]+$/.test(expression)) throw new Error('Unexpected bb arithmetic');
    // bb-generated trusted arithmetic, restricted to numeric expressions above.
    const value = Function(`"use strict"; return (${expression});`)();
    proofLength = match[1] === '=' ? value : proofLength + value;
  }
  if (!Number.isSafeInteger(proofLength) || proofLength <= 0) throw new Error('Invalid proof size');
  const call = 'uint256 expectedProofSize = calculateProofSize($LOG_N);';
  if (!source.includes(call)) throw new Error('Unexpected bb size check');
  source = source.replace(call, `uint256 expectedProofSize = ${proofLength};`)
    .replace(/\bHonkVerificationKey\b/g, 'MembershipVoteVerificationKey')
    .replace(/\bcontract HonkVerifier\b/g, 'contract MembershipVoteVerifier');
  source = source.replace('// Copyright 2022 Aztec', '// Copyright 2022 Aztec\n'
    + '// Generated by scripts/generate-verifier.mjs; do not edit.\n'
    + `// bb-derived proof size: ${proofLength} fields; Keccak oracle, zero knowledge.`);
  writeFileSync(outputPath, source);
  const manifestPath = join(artifactDirectory, 'manifest.json');
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  manifest.verifierSha256 = sha256(source);
  manifest.proofFields = proofLength;
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateVerifier();
}
